// Transactional email via Resend (https://resend.com), logged to shop_email_events.
// A dedupe key makes every send idempotent: a retried request or double-click
// never emails the customer twice. Email failures never roll back orders —
// they're logged and can be retried from the admin.
import { db } from './db.js'
import { escapeHtml as h } from './http.js'
import { formatCents as money } from './pricing.js'

const RESEND_API_KEY = Deno.env.get('RESEND_API_KEY')

/**
 * @param {object} p
 * @param {string} p.purpose
 * @param {string} p.to
 * @param {string} p.subject
 * @param {string} p.html
 * @param {string} [p.from]
 * @param {string} [p.replyTo]
 * @param {Array<{filename:string, content:string}>} [p.attachments]  base64 content
 * @param {string} [p.dedupeKey]
 * @param {boolean} [p.force]  resend even if already sent (admin "Resend")
 */
export async function sendEmail({ purpose, to, subject, html, from, replyTo, attachments, dedupeKey, force = false, orderId = null, projectId = null, invoiceId = null }) {
  let event = null
  if (dedupeKey) {
    const { data } = await db.from('shop_email_events').select('*').eq('dedupe_key', dedupeKey).maybeSingle()
    event = data
    if (event?.status === 'sent' && !force) return { status: 'sent', duplicate: true, event }
  }
  if (!event) {
    const { data, error } = await db.from('shop_email_events').insert({
      purpose, recipient: to, subject, order_id: orderId, project_id: projectId, invoice_id: invoiceId, dedupe_key: dedupeKey || null,
      payload: { html, from, replyTo, attachmentNames: (attachments || []).map(a => a.filename) },
    }).select().single()
    if (error) {
      // Lost a race with a concurrent identical send.
      if (error.code === '23505') return { status: 'sent', duplicate: true }
      console.error('email log failed', error)
    }
    event = data
  }

  if (!RESEND_API_KEY) {
    if (event) await db.from('shop_email_events').update({ status: 'skipped', error: 'RESEND_API_KEY not configured', attempts: (event.attempts || 0) + 1 }).eq('id', event.id)
    return { status: 'skipped', event }
  }

  try {
    const res = await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: { Authorization: `Bearer ${RESEND_API_KEY}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({ from, to: [to], subject, html, reply_to: replyTo || undefined, attachments: attachments?.length ? attachments : undefined }),
    })
    const body = await res.json().catch(() => ({}))
    if (!res.ok) throw new Error(body?.message || `Resend HTTP ${res.status}`)
    if (event) await db.from('shop_email_events').update({ status: 'sent', provider_id: body.id || null, error: null, sent_at: new Date().toISOString(), attempts: (event.attempts || 0) + 1 }).eq('id', event.id)
    return { status: 'sent', event }
  } catch (err) {
    console.error('email send failed', purpose, err)
    if (event) await db.from('shop_email_events').update({ status: 'failed', error: String(err.message || err), attempts: (event.attempts || 0) + 1 }).eq('id', event.id)
    return { status: 'failed', error: String(err.message || err), event }
  }
}

/** Re-sends a logged email (admin retry). Attachments are regenerated by the caller when needed. */
export async function retryEmail(eventId, { from }) {
  const { data: ev } = await db.from('shop_email_events').select('*').eq('id', eventId).single()
  if (!ev) return { status: 'failed', error: 'Not found' }
  return sendEmail({ purpose: ev.purpose, to: ev.recipient, subject: ev.subject, html: ev.payload?.html || '', from: ev.payload?.from || from, dedupeKey: ev.dedupe_key, force: true, orderId: ev.order_id, projectId: ev.project_id, invoiceId: ev.invoice_id })
}

