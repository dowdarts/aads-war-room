const p = s => `<p style="margin:0 0 12px;line-height:1.55">${s}</p>`
const btn = (href, label) => `<p style="margin:18px 0"><a href="${h(href)}" style="display:inline-block;background:#ff7a00;color:#140800;font-weight:800;text-decoration:none;padding:12px 18px;border-radius:10px">${h(label)}</a></p>`

export function itemsTable(items) {
  const rows = items.map(it => {
    const opts = [it.colour, it.size, it.closure === 'zipper' ? 'Zipper' : 'Button', it.pocket ? 'Pocket' : 'No pocket', it.personalization ? `Name: ${it.personalization}` : null].filter(Boolean).join(' · ')
    return `<tr><td style="padding:8px 0;border-bottom:1px solid #eee"><b>${it.qty}×</b> ${h(it.product_name)}<div style="color:#71717a;font-size:12px">${h(opts)}</div></td><td align="right" style="padding:8px 0;border-bottom:1px solid #eee;white-space:nowrap">${money(it.line_cents)}</td></tr>`
  }).join('')
  return `<table width="100%" cellpadding="0" cellspacing="0" style="font-size:14px;margin:8px 0 12px">${rows}</table>`
}

export function totalsTable(t) {
  const row = (label, val, bold) => `<tr><td style="padding:3px 0;${bold ? 'font-weight:900;font-size:16px' : ''}">${label}</td><td align="right" style="padding:3px 0;${bold ? 'font-weight:900;font-size:16px' : ''}">${val}</td></tr>`
  return `<table width="100%" cellpadding="0" cellspacing="0" style="font-size:14px;border-top:1px solid #eee;padding-top:6px">
${row('Subtotal', money(t.subtotal_cents + (t.discount_cents || 0)))}
${t.discount_cents ? row('Discount', '−' + money(t.discount_cents)) : ''}
${row('Shipping', t.shipping_cents ? money(t.shipping_cents) : 'Free')}
${t.tax_cents ? row('Tax', money(t.tax_cents)) : ''}
${row('Total', money(t.total_cents), true)}
${t.credits_cents ? row('Paid / credited', '−' + money(t.credits_cents)) : ''}
${t.balance_cents != null && t.credits_cents ? row('Balance due', money(t.balance_cents), true) : ''}
</table>`
}

export function paymentBlock(settings, reference, amountCents) {
  return `<div style="margin:16px 0;padding:14px 16px;border:1px solid #fed7aa;background:#fff7ed;border-radius:10px;font-size:14px;line-height:1.6">
<b>Pay by Interac e-Transfer</b><br>
Amount: <b>${money(amountCents)} CAD</b><br>
Send to: <b>${h(settings.etransfer_email || '')}</b><br>
Message: <b>${h(reference)}</b><br>
<span style="color:#9a3412">${h(settings.etransfer_instructions || '')}</span></div>`
}

